//go:build ignore

// Collects the licences of everything linked into the binary.
//
//	go run scripts/gen-notices.go      (or: just notices)
//
// Apache-2.0 section 4 requires that a redistribution carry the licence, the
// copyright notices, and any NOTICE file from the original. One of this
// binary's dependencies is Apache-2.0, so the obligation is real and it
// travels with the binary rather than living only in the repo. The BSD and
// MIT modules ask for their notice to be reproduced too; the file covers all
// of them rather than only the strictest.
//
// The module set is what is actually LINKED into ./cmd/nan, which is
// narrower than `go list -m all` — that reports the whole module graph,
// test-only and build-time dependencies included, and those never reach a
// user. Shipping notices for code that is not in the binary is not more
// careful, it is less accurate.
package main

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

// The binary whose linked dependencies are being collected.
const target = "./cmd/nan"

// out is written at the repo root, beside LICENSE, so it is obvious that the
// two travel together.
const out = "THIRD-PARTY-NOTICES.txt"

// licenceNames is what module authors actually call the file, most common
// first. The first hit in a module's root wins.
var licenceNames = []string{
	"LICENSE", "LICENCE", "LICENSE.md", "LICENSE.txt",
	"COPYING", "COPYING.md", "LICENSE-MIT",
}

type module struct{ path, version, dir string }

// embedded is third-party text compiled into the binary with go:embed, each
// directory holding the file, its LICENSE and its NOTICE.
var embedded = []struct{ name, what, dir string }{
	{"OpenAI Codex", "internal/tools/codexprompt/base_instructions.md, the prompt the Codex catalogue carries", "internal/tools/codexprompt"},
}

func main() {
	mods := linkedModules()
	if len(mods) == 0 {
		fail(fmt.Errorf("no modules found - has the build cache been populated? try `go build ./...` first"))
	}

	var body strings.Builder
	var toc strings.Builder
	counts := map[string]int{}

	for _, m := range mods {
		text, err := licenceOf(m)
		if err != nil {
			// A module with no licence file is not something to paper over:
			// it is either a packaging mistake upstream or a dependency
			// nobody has looked at.
			fail(fmt.Errorf("no licence file in %s %s (%s)", m.path, m.version, m.dir))
		}
		counts[classify(text)]++
		fmt.Fprintf(&toc, "  %-44s %s\n", m.path, m.version)
		rule := strings.Repeat("=", 78)
		fmt.Fprintf(&body, "%s\n%s\n%s\n%s\n\n%s\n\n", rule, m.path, m.version, rule, text)
	}

	// Files embedded in the binary that are not Go modules: the walk above
	// cannot see them, and their licence travels with them all the same.
	for _, e := range embedded {
		notice, err := os.ReadFile(e.dir + "/NOTICE")
		if err != nil {
			fail(err)
		}
		licence, err := os.ReadFile(e.dir + "/LICENSE")
		if err != nil {
			fail(err)
		}
		counts[classify(string(licence))]++
		fmt.Fprintf(&toc, "  %-44s %s\n", e.name, "(embedded)")
		rule := strings.Repeat("=", 78)
		fmt.Fprintf(&body, "%s\n%s\n%s\n%s\n\n%s\n\n%s\n\n", rule, e.name, e.what, rule,
			strings.TrimSpace(string(notice)), strings.TrimSpace(string(licence)))
	}

	var f strings.Builder
	fmt.Fprintf(&f, `Third-party notices for nan
%s

The distributed binary statically links the Go modules listed below and
embeds the files marked (embedded), and their licences are reproduced here
in full.

%s

This is the set actually linked into %s, which is narrower than
`+"`go list -m all`"+`: that reports the whole module graph, test-only and
build-time dependencies included, and those never reach a user.

Generated by scripts/gen-notices.go; run `+"`just notices`"+` after changing
dependencies.

Modules: %d
%s

%s
`, strings.Repeat("=", len("Third-party notices for nan")), apacheClause(counts), target, len(mods), summary(counts), toc.String())

	if err := os.WriteFile(out, []byte(f.String()+body.String()), 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("wrote %s - %d modules (%s)\n", out, len(mods), summary(counts))
}

// linkedModules is every module contributing a package to the binary, minus
// this one and the standard library.
func linkedModules() []module {
	pkgs := run("go", "list", "-deps", target)

	seen := map[string]module{}
	for _, pkg := range strings.Fields(pkgs) {
		if strings.HasPrefix(pkg, "github.com/nxssie/nan-cli") {
			continue
		}
		line := strings.TrimSpace(run("go", "list", "-f",
			"{{if .Module}}{{.Module.Path}}\t{{.Module.Version}}\t{{.Module.Dir}}{{end}}", pkg))
		if line == "" {
			continue // standard library: no module
		}
		parts := strings.Split(line, "\t")
		if len(parts) != 3 || parts[2] == "" {
			continue
		}
		seen[parts[0]] = module{parts[0], parts[1], parts[2]}
	}

	mods := make([]module, 0, len(seen))
	for _, m := range seen {
		mods = append(mods, m)
	}
	sort.Slice(mods, func(i, j int) bool {
		return strings.ToLower(mods[i].path) < strings.ToLower(mods[j].path)
	})
	return mods
}

func licenceOf(m module) (string, error) {
	for _, name := range licenceNames {
		if b, err := os.ReadFile(filepath.Join(m.dir, name)); err == nil {
			return strings.TrimRight(string(b), "\n"), nil
		}
	}
	return "", os.ErrNotExist
}

// classify is for the summary line only — enough to say what is in the file,
// not an SPDX detector.
func classify(text string) string {
	t := strings.ToLower(text)
	switch {
	case strings.Contains(t, "apache license") && strings.Contains(t, "2.0"):
		return "Apache-2.0"
	case strings.Contains(t, "permission is hereby granted, free of charge"):
		return "MIT"
	case strings.Contains(t, "redistributions of source code must retain"):
		if strings.Contains(t, "neither the name") {
			return "BSD-3-Clause"
		}
		return "BSD-2-Clause"
	case strings.Contains(t, "permission to use, copy, modify, and/or distribute"):
		return "ISC"
	}
	return "other"
}

func summary(counts map[string]int) string {
	keys := make([]string, 0, len(counts))
	for k := range counts {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	parts := make([]string, 0, len(keys))
	for _, k := range keys {
		parts = append(parts, fmt.Sprintf("%d %s", counts[k], k))
	}
	return strings.Join(parts, ", ")
}

// apacheClause names the licence that makes this file an obligation rather
// than a courtesy, and says so only when one is actually linked.
func apacheClause(counts map[string]int) string {
	switch n := counts["Apache-2.0"]; n {
	case 0:
		return "None of them is Apache-2.0 today, so this file is a courtesy\n" +
			"rather than an obligation. The MIT and BSD notices still belong\n" +
			"with the binary."
	case 1:
		return "One of them is Apache-2.0, whose section 4 requires this of any\n" +
			"redistribution. The rest are reproduced alongside it rather than\n" +
			"sorting the obligation per module."
	default:
		return fmt.Sprintf("%d of them are Apache-2.0, whose section 4 requires this of\n"+
			"any redistribution. The rest are reproduced alongside them rather\n"+
			"than sorting the obligation per module.", n)
	}
}

func run(name string, args ...string) string {
	cmd := exec.Command(name, args...)
	var out, errBuf bytes.Buffer
	cmd.Stdout = &out
	cmd.Stderr = &errBuf
	if err := cmd.Run(); err != nil {
		fail(fmt.Errorf("%s %s: %w: %s", name, strings.Join(args, " "), err, errBuf.String()))
	}
	return out.String()
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "error:", err)
	os.Exit(1)
}
